"""Audit prompts."""

from .policies import DECISION_POLICY, TERM_POLICY

AUDIT_HEADER = "【任务】AUDIT问题审查"


NAME_CHECK_HEADER = "【任务】TERM专名核验"


AUDIT_SYSTEM = (
    "你是严谨的学术论文审稿专家（Audit Agent）。"
    "你只负责系统性地发现问题，不负责改写论文。"
    "你给出的evidence必须是原文中逐字出现的片段，并且必须指明它所在的段落ID。"
    "始终只输出合法JSON，不要输出多余解释。"
)


NAME_CHECK_SYSTEM = (
    "你是学术论文的术语校对员（Term Checker）。"
    "先结合术语所在章节、段落与前后文辨认所指对象，再判断该位置是否用错。"
    "每条判断必须引用该段的具体定义或方法描述，说明语义矛盾；领域知识只作辅助。"
    "出现次数和拼写相近都不是错误证据。同一术语的其他位置必须分别判断，代码不改。"
    "没有把握的一律不要报。始终只输出合法JSON，不要输出多余解释。"
)


def render_audit_prompt(context_text: str) -> str:
    """Audit Prompt（带段落ID的文本）。"""

    return f"""{AUDIT_HEADER}

{TERM_POLICY}
{DECISION_POLICY}

# 上下文
{context_text}

# 审查要求
请审查上面的“待处理文本”，找出其中**真实存在**的问题。
文本里的每个块都有形如 [P03] / [H02] / [T01] 的段落ID，
你的每一条问题都必须指明它属于哪个段落。

重点关注：
1. 语言表达（语法、病句、表达不清、指代不明）
2. 术语使用（术语不统一、用词不专业）
3. 逻辑结构（论证跳跃、前后矛盾、缺乏过渡）
4. 方法描述（方法交代不清、缺少必要细节、可复现性不足）
5. 实验分析（结果分析不足、结论与数据不匹配、缺少对比讨论）
6. 结论（结论过度推断、与结果不符）
7. 学术规范（引用格式、图表说明、客观表述）
8. 降重（重复表达、冗余啰嗦）
9. 专有名词（方法名、模型名、数据集名、机构名、人名与缩写）：
   同一个东西在全文有没有写成两种样子（大小写、连字符、全称/缩写混用）；
   拼写是否与领域惯例一致（例如PubMed写成Pubmed、GraphSAGE写成Graph-SAGE、
   ResNet写成resnet）；首次出现是否给出全称、之后是否统一用缩写；
   中英文混排时是否误用了音译或自造译名。

# 输出格式（只输出JSON）
{{
  "issues": [
    {{
      "span_label": "P03",
      "kind": "fix | decision",
      "options": ["仅在kind=decision时给出：2~3个可选项，供作者直接勾选"],
      "other_labels": ["仅在kind=decision时给出：矛盾的另一处段落ID（例如P183）"],
      "span_labels": ["同一条问题涉及的全部段落ID（例如P26、P28、P45）；只涉及一处时可省略"],
      "category": "语言表达 | 术语使用 | 逻辑结构 | 方法描述 | 实验分析 | 结论 | 学术规范 | 降重 | 专有名词",
      "severity": "high | medium | low",
      "location": "问题所在位置（可写章节或段落特征）",
      "problem": "问题是什么，为什么是问题",
      "evidence": "该段落里逐字出现的片段（不要改写、不要省略号）",
      "suggestion": "修改方向（不要直接改写整段）"
    }}
  ]
}}

# 硬约束
- span_label必须来自上面文本中真实存在的标签。
- **每条问题都要标一个kind，按下面三条判据选**：
  · `"fix"`：原文**确实写错了**，有唯一正确的改法——错别字、乱码、
    多余字符、缺失标点、数值明显写错。**客观上只有一种改法**才是fix。
    这类会被自动修改，不需要作者参与。
  · `"decision"`：**没有唯一正确答案，只有作者能定**——
    · 同一个名称在全文有几种写法（MoCo / MOCO），该统一成哪一种；
    · 两处说法互相冲突（正文0.09、参数表0.07），以哪一处为准；
    · 同一个百分比在两处对应不同实验设置。
    判据一句话：**"改A还是改B"取决于作者的偏好或实验事实** → decision。
    这类不自动改，会拿去让作者拍板。
    注意：**术语写法不统一属于decision，不属于fix** ——
    MoCo和MOCO都是合法写法，没有客观对错，必须让作者选。
  · 不再输出独立的建议类别。合理改进使用fix并给具体方案，由后续补丁交作者确认。
  不确定是否有问题时不报，不把猜测包装成待办。
- **一个问题可以带多个位置**：如果同一件事在好几段都出现，
  `span_labels`里把它们**全部**列出来（例如`["P26","P28","P45","P50"]`），
  `span_label`填第一个即可。
  **"不重复报"指的是同一个问题只写一条、不要每段各报一条——
  不是只能给一个标号。** 位置列得越全，后面越不会漏改。
- evidence必须逐字来自该段落，长度15~120字，并且在该段落内唯一
  （系统会逐字核对；找不到原文依据的问题会被直接丢弃）。
- **同一类系统性问题只报一条**：例如"参考文献格式不统一"在十几处出现时，
  只输出一条，evidence给一个代表片段，并在problem里列出其它涉及段落（如"另见P581、P583"）。
  绝不要每段各报一条。
- **专有名词只报"有依据"的**：必须能在文本里指出冲突（同一个词有另一种写法、
  与表格/图注里的写法不一致），或指出明显拼写错误。不要凭印象把正确的专有名词"改成"
  你以为的写法；不确定时用suggestion提示作者核对，而不要断言。category用"专有名词"。
- **判断缩写是否写错，必须回到上下文，不能只看出现次数。**
  出现次数少 ≠ 写错。GNN / KNN / CNN / RNN是四个互不相同的真实术语，
  不同章节出现不同的缩写是完全正常的。只有能指出"这两处指的是**同一个对象**"时，
  才算写法不一致。判断依据是：那句话在讲什么、它引用的文献是哪一篇。
- **缩写与全称**：只要**中文摘要与英文摘要**里都用简称（不给全称），
  全称只在**正文**（第一章之后）**第一次出现**处标注一次，写成`MoCo（Momentum Contrast）`，
  之后一律只写简称，不要重复标注。
- **判断一个缩写是不是写错，只能看它所在的那句话**：把它放回原句读一遍，
  看这个词在那个位置上讲不讲得通。
  例：「尝试运用Transformer[4]、GNN[5] 等**网络结构**」——GNN就是网络结构，
  句子成立，**这是对的，不要报**；换成KNN反而不通（KNN不是网络结构）。
  出现次数少 ≠ 写错，"全文别处写的是另一个"也不是依据。
  **放进句子里说得通，就不要报。**
- **英文摘要只跟随中文摘要**：中文摘要没改就不要动英文摘要；
  中文摘要改了，英文摘要只做对应翻译，不要顺带改别的内容。
- 上文如果给出「一致性核对提示（确定性检查）」，那是系统**扫描全文**得到的真实结果
  （分批评审看不到的，这里能看到），请逐条核对：
  · 同一个词多种写法 → 判断哪种正确，**合并成一条**，在problem里列全涉及的段落；
  · 「只在摘要或结论出现、正文从未出现」的方法名/数据集名 → 这是最值得报的一类：
    要么正文缺了对应的实验/方法说明，要么总结里写了正文没做过的东西，
    用category「专有名词」报出，并在suggestion里写清两条路怎么选；
  · 「疑似拼写错误」→ 提示作者核对，不要直接断言哪个对。
    注意：这个提示只说明"看起来像"，**不是结论**。必须回到上下文核实——
    看那个缩写出现的那句话在讲什么、引用的文献是哪一篇。
    像GNN / KNN / CNN / RNN这种都是真实存在的独立术语，
    **绝不能只因为某一个全文只出现一次就判它是笔误**；
    拿不出"两处指同一个对象"的证据，就不要报。
  但如果差异只是排版风格（例如标题里的全大写、图表标题的编号格式），不要报。
- evidence里不要把段落开头的`###`、`-`、`|`这些**排版标记**当成正文引用，
  从标记后面的文字开始引用（那些标记是系统加的，正文里并不存在）。
- 只报影响论文质量的问题。以下一律不报：标点/空格偏好、个人写作风格、
  单纯的措辞不够漂亮、"可以写得更详细"这类没有具体依据的泛泛建议。
  如果要建议补充细节，必须说清缺的是哪一项具体信息（例如"未说明学习率与训练轮数"）。
- **不要审代码。** 多行的程序清单（含def / for / if / self. 这类语句的段落）里的内容
  一律不要报——你读到的是**抽取出来的文本**，上下文往往不全
  （模块级常量、被引用的定义常常没写进论文），判断不了代码对不对。
  代码留给作者自己核对。
- 涉及**数值口径 / 表述含义**的问题，suggestion要写**怎么改正文**——
  例如让同一个数值前后只对应一种口径、删掉重复的表述。
  **不要**建议"加括号说明""补一句解释""标注口径"：往正文里插解释属于画蛇添足，
  Revision会按这个建议去扩写，反而把论文改坏。
  如果你认为只有作者才能决定以哪个口径为准，就在problem里说清楚，
  并让suggestion写成"请作者确认以哪一处为准"。
- severity的含义：high = 影响结论正确性或可复现性；medium = 影响读者理解；
  low = 可改可不改（这类尽量不报）。
- 没有问题就返回空数组：**没有发现就是没有发现，宁可少报，也不要凑数**。
- 最多输出3条问题（同一类系统性问题算一条），按严重程度从高到低排列。
"""


def render_name_check_prompt(context_text: str) -> str:
    """逐个术语、逐个位置判断语义，不按出现次数或形近程度判断。"""
    return f"""{NAME_CHECK_HEADER}

# 上下文
{context_text}

# 任务
根据每个术语所在的章节、完整段落和前后段，判断它在该位置是否用错。
先辨认本段实际讨论的对象、方法、定义或产品，再判断术语与这个对象是否一致。
领域知识可以辅助理解；原文的明确语义才是此处需要修改的依据。

- GNN、KNN、CNN、RNN可以是不同的方法，即使只有GNN出现一次也不构成错误。
- 例如：段落讲图上的消息传递时，不能因为全文KNN多就把GNN改为KNN；
  段落明确把“k近邻分类器”缩写成GNN时，才可能有具体的修改依据。
- 同一个缩写在不同段落可以指不同对象。发现一处用错，不得自动推导全文都错。
- CNN也可能用于序列任务，不能凭“通常用于某任务”排除原文用法。
- 频次、拼写相似、只差一个字母、正文缺少同名词均不能作为判错依据。
- 代码及变量名不提出替换。上下文不足、不同解释均合理时不报错。

# 输出格式（只输出JSON）
{{
  "suspected": [
    {{
      "name": "清单中的术语",
      "correct": "此处应使用的术语",
      "span_label": "确切的段落标号，例如P20",
      "evidence": "该段落逐字原文，包含术语和能判断语义的语句",
      "context_basis": "该段落逐字引用的定义或方法描述，不能只有术语本身",
      "reason": "解释原文描述的对象是什么，以及为什么此处术语与它矛盾，不能用次数或形近解释",
      "confidence": "high"
    }}
  ]
}}

只返回有明确语义依据的具体位置；不能确定就返回空数组。不要把一处结论扩散到全文。
"""
